export function siteCopy(locale: string): SiteCopy {
  const values = rows[locale];
  if (!values || values.length !== keys.length)
    throw new Error(`Incomplete website translation: ${locale}`);
  return Object.fromEntries(keys.map((key, index) => [key, values[index]!])) as SiteCopy;
}
